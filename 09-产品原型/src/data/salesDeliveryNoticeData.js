export function getDeliveryNoticeStatusBadges(row) {
  const toneMap = {
    pending_push: 'warning',
    pushing: 'info',
    push_failed: 'danger',
    pending_ship: 'info',
    cancelling: 'warning',
    shipped: 'success',
    cancelled: 'danger',
  };
  return [{ label: noticeStatusLabels[row.status] || row.status, tone: toneMap[row.status] || 'default' }];
}

