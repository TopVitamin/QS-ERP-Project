export function buildSourceReturnFilterOptions(rows = []) {
  const map = new Map();
  rows.forEach((row) => {
    if (!row.sourceReturnNo) return;
    map.set(row.sourceReturnNo, { value: row.sourceReturnNo, label: row.sourceReturnNo });
  });
  return [{ value: '', label: '全部' }, ...map.values()];
}
