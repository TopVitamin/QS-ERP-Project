export function getNoticeStatusBadges(row) {
  const toneMap = {
    pending_push: 'warning',
    pushing: 'info',
    push_failed: 'danger',
    pending_receive: 'info',
    cancelling: 'warning',
    received: 'success',
    cancelled: 'danger',
  };
  return [{ label: noticeStatusLabels[row.status] || row.status, tone: toneMap[row.status] || 'default' }];
}

