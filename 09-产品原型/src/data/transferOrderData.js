export function getEditableTransferOrder(row) {
  if (!row) {
    return { ...defaultTransferOrderForm, lines: defaultTransferOrderForm.lines.map((line) => ({ ...line })) };
  }
  return {
    ...defaultTransferOrderForm,
    id: row.id || '',
    orderNo: row.orderNo || defaultTransferOrderForm.orderNo,
    outWarehouse: row.outWarehouse || '',
    inWarehouse: row.inWarehouse || '',
    remark: row.remark ?? '',
    lines: (row.lines || []).map((line) => ({ ...line })),
  };
}
